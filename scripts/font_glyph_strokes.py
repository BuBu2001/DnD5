# Кириллические знаки, совпадающие по начертанию с латиницей
LATIN_LOOKALIKE = {'А':'A','В':'B','С':'C','Е':'E','Н':'H','К':'K','М':'M','О':'O',
                   'Р':'P','Т':'T','Х':'X'}

def build_glyph_map():
    """codepoint → (список отрезков, шаг в единицах сетки)"""
    glyphs = {}
    for code in range(32, 127):
        ch = chr(code)
        if ch in STROKES:
            glyphs[code] = STROKES[ch]
        elif ch.islower() and ch.upper() in STROKES:
            glyphs[code] = STROKES[ch.upper()]  # строчные = прописные (инженерный стиль)
    for i, ch in enumerate(CYR_UP):
        code = 0x0410 + i
        glyphs[code] = STROKES[ch] if ch in STROKES else STROKES[LATIN_LOOKALIKE.get(ch, '?')]
    for i, ch in enumerate(CYR_LO):
        code = 0x0430 + i
        if ch in STROKES:
            glyphs[code] = STROKES[ch]
        else:
            up = CYR_UP[i]
            glyphs[code] = STROKES[up] if up in STROKES else STROKES[LATIN_LOOKALIKE.get(up, '?')]
    glyphs[0x0401] = STROKES['Ё']
    glyphs[0x0451] = STROKES['ё']
    return glyphs

